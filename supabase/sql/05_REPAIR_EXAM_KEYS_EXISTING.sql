-- GradeDock: non-destructive repair for an EXISTING GradeDock project.
-- Use only if public.exams exists but public.exam_keys is missing or lacks access policies.
-- Preserves existing exams, keys, students, scores, and results. No DROP TABLE.
-- Back up your database before migrations. Run the entire file in SQL Editor.
BEGIN;

DO $$
BEGIN
  IF to_regclass('public.exams') IS NULL THEN
    RAISE EXCEPTION 'public.exams is missing. This is not a key-only repair. For a brand-new empty GradeDock project run sql/01_COMPLETE_SUPABASE_SETUP.sql.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.exam_keys (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exam_id uuid NOT NULL REFERENCES public.exams(id) ON DELETE CASCADE,
  question_number integer NOT NULL,
  correct_answer text NOT NULL CHECK (correct_answer IN ('A','B','C','D','E')),
  UNIQUE (exam_id, question_number)
);

-- Required by the frontend's safe answer-key UPSERT.
CREATE UNIQUE INDEX IF NOT EXISTS gradedock_exam_keys_exam_question_unique_idx
  ON public.exam_keys(exam_id, question_number);
CREATE INDEX IF NOT EXISTS exam_keys_exam_idx ON public.exam_keys(exam_id);
ALTER TABLE public.exam_keys ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "exam_keys_select_owned_exam" ON public.exam_keys;
DROP POLICY IF EXISTS "exam_keys_insert_owned_exam" ON public.exam_keys;
DROP POLICY IF EXISTS "exam_keys_update_owned_exam" ON public.exam_keys;
DROP POLICY IF EXISTS "exam_keys_delete_owned_exam" ON public.exam_keys;

CREATE POLICY "exam_keys_select_owned_exam" ON public.exam_keys FOR SELECT TO authenticated
USING (EXISTS (SELECT 1 FROM public.exams e WHERE e.id=exam_keys.exam_id AND e.teacher_id=(SELECT auth.uid())));
CREATE POLICY "exam_keys_insert_owned_exam" ON public.exam_keys FOR INSERT TO authenticated
WITH CHECK (EXISTS (SELECT 1 FROM public.exams e WHERE e.id=exam_keys.exam_id AND e.teacher_id=(SELECT auth.uid())));
CREATE POLICY "exam_keys_update_owned_exam" ON public.exam_keys FOR UPDATE TO authenticated
USING (EXISTS (SELECT 1 FROM public.exams e WHERE e.id=exam_keys.exam_id AND e.teacher_id=(SELECT auth.uid())))
WITH CHECK (EXISTS (SELECT 1 FROM public.exams e WHERE e.id=exam_keys.exam_id AND e.teacher_id=(SELECT auth.uid())));
CREATE POLICY "exam_keys_delete_owned_exam" ON public.exam_keys FOR DELETE TO authenticated
USING (EXISTS (SELECT 1 FROM public.exams e WHERE e.id=exam_keys.exam_id AND e.teacher_id=(SELECT auth.uid())));

GRANT USAGE ON SCHEMA public TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.exam_keys TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

COMMIT;
NOTIFY pgrst, 'reload schema';
